#include <iostream>

int main()
{
	std::cout << " 아스키 코드 출력하기 [32 ~ 126]: \n";

	for (char i = 32; i <= 126; i++) //32부터 126까지 1씩 증가
	{
		// 아스키 코드를 출력할때 공백을 넣고 16개마다 줄 바꾸기
		std::cout << i << ((i%16 == 15) ? '\n' : ' ');
		// i를 16으로 나눈 나머지를구하고 나머지가 15이면 줄바꿈 아니면 공백
		// ?과 : 는 삼항 연산자
		//조건식 ? 참일_때_선택할_값 : 거짓일_때_선택할_값
	}

	return 0;

}